type Lang = "en" | "fr" | "es" | "ru";

interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: (key: string) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");

  useEffect(() => {
    const saved = localStorage.getItem("esl-lang") as Lang;
    if (saved && translations[saved]) setLang(saved);
  }, []);

  function changeLang(l: Lang) {
    setLang(l);
    localStorage.setItem("esl-lang", l);
  }

  function t(key: string) {
    return translations[lang]?.[key] || translations.en[key] || key;
  }

  return (
    <I18nContext.Provider value={{ lang, setLang: changeLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() { return useContext(I18nContext); }

export function LangSwitcher() {
  const { lang, setLang } = useI18n();
  const langs: { code: Lang; flag: string }[] = [
    { code: "en", flag: "EN" },
    { code: "fr", flag: "FR" },
    { code: "es", flag: "ES" },
    { code: "ru", flag: "RU" },
  ];
  return (
    <div className="flex items-center gap-1">
      {langs.map(l => (
        <button key={l.code} onClick={() => setLang(l.code)}
          className={`px-2 py-1 rounded text-xs font-bold transition-all ${lang === l.code ? "bg-brand-500 text-white" : "bg-slate-100 text-slate-500 hover:bg-slate-200"}`}>
          {l.flag}
        </button>
      ))}
    </div>
  );
}
